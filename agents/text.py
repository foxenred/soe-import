"""Текст агента для человека: даты словами, десятичная запятая, неразрывный пробел перед %, без формульных обозначений."""
from __future__ import annotations

import re

MONTHS = ["янв.", "февр.", "марта", "апр.", "мая", "июня", "июля", "авг.", "сент.", "окт.", "нояб.", "дек."]

PLAIN = (("выгода E[B]", "чистая выгода"), ("Выгода E[B]", "Чистая выгода"), ("E[B]", "чистая выгода"),
         ("Правило P2", "Расчетное правило"), ("(P0)", ""), ("(P1)", ""), ("(P2)", ""), ("коридор расходов", "лимит региона"),
         ("Интервал прибытия P10–P90", "Вероятный срок прибытия"), ("интервал прибытия P10–P90", "вероятный срок прибытия"),
         ("Интервал прибытия", "Вероятный срок прибытия"), ("интервал прибытия", "вероятный срок прибытия"),
         ("P10–P90", "вероятный срок"), ("P10-P90", "вероятный срок"),
         ("правилу P2", "расчетному правилу"), ("правила P2", "расчетного правила"), ("правило P2", "расчетное правило"),
         ("в коридоре", "в пределах лимита"), ("вне коридора", "выше лимита"), ("коридора", "лимита"), ("коридор", "лимит"),
         ("ожидаемая выгода", "чистая выгода"), ("Ожидаемая выгода", "Чистая выгода"), ("ожидаемой выгоды", "чистой выгоды"),
         ("ожидаемой выгодой", "чистой выгодой"), ("ожидаемую выгоду", "чистую выгоду"),
         ("шт./день", "шт. в день"), ("шт/день", "шт. в день"), ("шт/день", "шт. в день"))


MONTHS_FULL = ("января", "февраля", "марта", "апреля", "мая", "июня", "июля", "августа", "сентября", "октября", "ноября", "декабря")


def plain(text: str) -> str:
    """Текст для пользователя: без буквы с двумя точками и без формульных обозначений (правила проекта)."""
    t = (text or "").replace("\u0451", "е").replace("\u0401", "Е")
    for a, b in PLAIN:
        t = t.replace(a, b)
    t = re.sub(r"\b(\d{4})-(\d{2})-(\d{2})\b", lambda m: f"{int(m.group(3))} {MONTHS_FULL[int(m.group(2)) - 1]}", t)   # 2026-11-29 → 29 ноября
    t = re.sub(r"(?<![\d.])(\d+)\.(\d+)(?![\d.])", "\\1,\\2", t)          # 0.9 → 0,9
    t = re.sub(r"(?<![\w-])-(\d)", "\u2212\\1", t)          # минус вместо дефиса: -9 → −9
    t = re.sub(r"(\d)\s?%", "\\1\u00a0%", t)                 # 30% → 30 % (неразрывный пробел)
    t = re.sub(r"\s+([,.;:])", r"\1", t)
    return t
